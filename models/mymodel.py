class MyModel(nn.Module):
    def __init__(self):
        super(MyModel, self).__init__()
        self.convin = nn.Conv2d(3,64,3,padding=1)
        self.convout = nn.Conv2d(64,3,3,padding=1)
        # 1. 入口卷积：3 → 64
        # 2. 出口卷积：64 → 3

    def forward(self, x):
        y = x
        x = self.convin(x)
        x = self.convout(x)
        x = y-x
        return(x)
        # 1. 存下原图
        # 2. 入口卷积 → 出口卷积，得到「雨层」
        # 3. 原图 − 雨层，返回
